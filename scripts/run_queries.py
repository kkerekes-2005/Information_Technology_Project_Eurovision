"""Run every query of sql/queries/ with its example parameters and write docs/queries.md.

    python scripts/run_queries.py

Each query file starts with four comment lines: the question, the constructs, the
example parameters and the meaning. This script only sends the SQL to PostgreSQL
and copies the rows it gets back into the document. It calculates nothing.
"""
import glob
import os
import sys

sys.path.insert(0, "src")
from db import run_query  # noqa: E402

AUTHOR = "Kinga Kerekes"
SAMPLE_ROWS = 8


def parse(path):
    """Split a query file into its header fields and the SQL text."""
    header, sql_lines = {}, []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("-- Q"):
                header["id"], header["question"] = line[3:].strip().split(". ", 1)
            elif line.startswith("-- Constructs:"):
                header["constructs"] = line.split(":", 1)[1].strip()
            elif line.startswith("-- Parameters:"):
                header["parameters"] = line.split(":", 1)[1].strip()
            elif line.startswith("-- Meaning:"):
                header["meaning"] = line.split(":", 1)[1].strip()
            else:
                sql_lines.append(line)
    return header, "".join(sql_lines).strip()


def parse_parameters(text):
    """'country=se; top_n=5; countries=[se,ie]' -> {'country': 'se', 'top_n': 5, ...}"""
    params = {}
    if text == "none":
        return params
    for part in text.split(";"):
        name, value = part.strip().split("=")
        if value.startswith("["):
            params[name] = value.strip("[]").split(",")
        elif value.isdigit():
            params[name] = int(value)
        else:
            params[name] = value
    return params


def literal(value):
    """A parameter value written as SQL text, only to show a runnable query in the document."""
    if isinstance(value, list):
        return "ARRAY[" + ", ".join(f"'{v}'" for v in value) + "]"
    if isinstance(value, int):
        return str(value)
    return f"'{value}'"


def as_table(rows):
    if not rows:
        return "(no rows)"
    columns = list(rows[0].keys())
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    for row in rows[:SAMPLE_ROWS]:
        lines.append("| " + " | ".join("" if row[c] is None else str(row[c]) for c in columns) + " |")
    return "\n".join(lines)


def main():
    out = ["# SQL queries", "",
           "Generated by `scripts/run_queries.py` from the files in `sql/queries/`. "
           "The SQL shown has the example parameter values written in, so it can be pasted "
           "into the pgAdmin Query Tool. In the application the same SQL runs with named "
           "parameters (`:name`).", ""]
    for path in sorted(glob.glob("sql/queries/q*.sql")):
        header, sql = parse(path)
        if "parameters" not in header:
            # The transaction script changes data, so it is run by hand, part by part.
            out += [f"## {header['id']}. {header['question']}", "",
                    f"Author: {AUTHOR}. File: `{path.replace(os.sep, '/')}`. "
                    f"Constructs: {header['constructs']}", "",
                    "```sql", sql, "```", "",
                    "Result: run by hand in pgAdmin, one part at a time. Part 1 inserts 4 rows. "
                    "Part 2 stops with a CHECK violation on `vote` and, after ROLLBACK, the "
                    "check shows running_order 21 and 0 votes. Part 3 deletes the 4 rows.", "",
                    f"Why it is meaningful: {header['meaning']}", ""]
            print(f"{header['id']}: not run (changes data)")
            continue
        params = parse_parameters(header["parameters"])
        rows = run_query(sql, params)
        shown = sql
        for name in sorted(params, key=len, reverse=True):
            shown = shown.replace(f":{name}", literal(params[name]))
        out += [f"## {header['id']}. {header['question']}", "",
                f"Author: {AUTHOR}. File: `{path.replace(os.sep, '/')}`. "
                f"Constructs: {header['constructs']}", "",
                "```sql", shown, "```", "",
                f"Result: {len(rows)} rows. First {min(len(rows), SAMPLE_ROWS)}:", "",
                as_table(rows), "",
                f"Why it is meaningful: {header['meaning']}", ""]
        print(f"{header['id']}: {len(rows)} rows")
    with open("docs/queries.md", "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("docs/queries.md written")


if __name__ == "__main__":
    main()
